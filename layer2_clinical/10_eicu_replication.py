#!/usr/bin/env python3
"""eICU replication: the mortality endpoint, and the APACHE IVa benchmark.

SPEC.md §4.5d2 and §4.4. This is the harder transfer: a different schema
entirely, where "variable definitions and units will not line up cleanly, and
that friction is itself informative about deployability."

Two things only this dataset can provide:

  MORTALITY — Challenge 2019 has no death outcome at all (§6.1). eICU has
  hospitaldischargestatus. The n is thin and the intervals will be wide; they
  are reported wide.

  AN EXTERNAL PUBLISHED MODEL — apachePatientResult ships APACHE IVa's own
  predicted hospital mortality, generated by someone else's model. Benchmarking
  against it is the C2 anchor (D13), and it is stronger than reimplementing an
  equation because there is no way to have reimplemented it favourably.

UNITS ARE VERIFIED, NOT ASSUMED. eICU names labs differently ("WBC x 1000",
"platelets x 1000", "bicarbonate") and charts FiO2 as a percentage where
Challenge 2019 uses a fraction. Every mapped variable is range-checked against
its Challenge distribution before use, and a mismatch stops the script.

Usage
-----
    python layer2_clinical/10_eicu_replication.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd
import yaml
from scipy import stats
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from shared import paths
from shared.assertions import CheckpointError, report_only
from shared.logging_setup import setup, set_seeds, step

log = setup("L2_eicu")

# eICU labname -> our feature name. Verified against the lab table, not guessed.
LAB_MAP = {
    "bicarbonate": "HCO3",
    "creatinine": "Creatinine",
    "BUN": "BUN",
    "glucose": "Glucose",
    "potassium": "Potassium",
    "Hgb": "Hgb",
    "Hct": "Hct",
    "WBC x 1000": "WBC",
    "platelets x 1000": "Platelets",
}
VITAL_MAP = {
    "heartrate": "HR", "sao2": "O2Sat", "respiration": "Resp",
    "systemicmean": "MAP", "temperature": "Temp", "systemicsystolic": "SBP",
}
# Plausible ranges, used to catch a unit mismatch between the two datasets.
PLAUSIBLE = {
    "HCO3": (5, 50), "Creatinine": (0.1, 20), "BUN": (1, 200),
    "Glucose": (20, 1000), "Potassium": (1.5, 9), "Hgb": (3, 22),
    "Hct": (10, 65), "WBC": (0.1, 100), "Platelets": (5, 1000),
    "HR": (20, 250), "O2Sat": (50, 100), "Resp": (2, 60),
    "MAP": (20, 180), "Temp": (30, 43), "SBP": (40, 260),
}


def connect():
    con = duckdb.connect(str(paths.DUCKDB))
    con.execute("SET memory_limit='6GB'")
    con.execute(f"SET temp_directory='{paths.SCRATCH}'")
    return con


def verify_units(df: pd.DataFrame, where: str) -> None:
    """A mapped variable outside its plausible range is a unit error, not data."""
    problems = []
    for col, (lo, hi) in PLAUSIBLE.items():
        if col not in df.columns:
            continue
        s = pd.to_numeric(df[col], errors="coerce").dropna()
        if s.empty:
            continue
        med = float(s.median())
        if not (lo <= med <= hi):
            problems.append(f"{col}: median {med:.2f} outside plausible [{lo}, {hi}]")
    if problems:
        raise CheckpointError(
            f"{where}: unit mismatch between eICU and Challenge 2019 —\n  "
            + "\n  ".join(problems)
            + "\nMap the units explicitly rather than letting the model see a "
              "differently-scaled variable than it was trained on.")
    log.info("✓ %s: all mapped variables within Challenge-comparable ranges", where)


def main() -> int:
    cfg = yaml.safe_load((paths.CONFIG / "cohort_params.yaml").read_text())
    inc, exc = cfg["inclusion"], cfg["exclusion"]
    fio2v = cfg["fio2_validity"]
    seed = set_seeds(cfg["clustering"]["seed"])
    con = connect()

    # --- FiO2: eICU charts it as a percentage, Challenge as a fraction ------
    with step(log, "FiO2 scale check"):
        fio2 = con.execute("""
            SELECT patientunitstayid, respchartoffset AS chart_offset,
                   TRY_CAST(respchartvalue AS DOUBLE) AS fio2_raw
            FROM eicu_resp
            WHERE respchartvaluelabel IN ('FiO2', 'FIO2 (%)')
              AND TRY_CAST(respchartvalue AS DOUBLE) IS NOT NULL
        """).df()
        med = fio2.fio2_raw.median()
        log.info("  raw FiO2 median %.2f over %d records, %d stays",
                 med, len(fio2), fio2.patientunitstayid.nunique())
        if med > 1.5:
            fio2["fio2"] = fio2.fio2_raw / 100.0
            log.warning("  eICU FiO2 is a PERCENTAGE; divided by 100 to match the "
                        "fraction scale the model was trained on. This is exactly the "
                        "schema friction §4.5d2 predicts, and getting it wrong would "
                        "make every S/F ratio 100x too large.")
        else:
            fio2["fio2"] = fio2.fio2_raw
        fio2 = fio2[fio2.fio2.between(fio2v["min"], fio2v["max"])]     # D10
        log.info("  usable FiO2 records after validity window: %d (%d stays)",
                 len(fio2), fio2.patientunitstayid.nunique())

    # --- cohort: first hour with S/F <= threshold ---------------------------
    with step(log, "eICU hypoxemic cohort"):
        con.register("fio2_tbl", fio2[["patientunitstayid", "chart_offset", "fio2"]])
        cohort = con.execute(f"""
            WITH sf AS (
                SELECT f.patientunitstayid, f.chart_offset, f.fio2, v.sao2,
                       v.sao2 / f.fio2 AS sf_ratio
                FROM fio2_tbl f
                JOIN eicu_vital v
                  ON v.patientunitstayid = f.patientunitstayid
                 AND ABS(v.observationoffset - f.chart_offset) <= 60
                WHERE v.sao2 IS NOT NULL AND v.sao2 > 0
                  AND v.sao2 < {exc['o2sat_saturation_cutoff']}
                  AND f.chart_offset BETWEEN 0 AND {exc['max_qualifying_hour'] * 60}
            )
            SELECT patientunitstayid, MIN(chart_offset) AS t0_offset, MIN(sf_ratio) AS min_sf
            FROM sf WHERE sf_ratio <= {inc['sf_ratio_threshold']}
            GROUP BY patientunitstayid
        """).df()
        log.info("  eICU stays meeting S/F <= %d: %d",
                 inc["sf_ratio_threshold"], len(cohort))
        report_only("eicu_cohort_n", len(cohort))
        if len(cohort) < 30:
            raise CheckpointError(
                f"only {len(cohort)} eICU stays qualify — too few for any estimate. "
                "§6.1 says leave the mortality question open rather than "
                "manufacture a substitute.")

    # --- features over T0 .. T0+24h -----------------------------------------
    with step(log, "eICU features"):
        con.register("cohort_tbl", cohort)
        lab_case = " ".join(
            f"WHEN l.labname = '{k}' THEN '{v}'" for k, v in LAB_MAP.items())
        labs = con.execute(f"""
            SELECT c.patientunitstayid,
                   CASE {lab_case} END AS feat,
                   AVG(TRY_CAST(l.labresult AS DOUBLE)) AS val
            FROM cohort_tbl c
            JOIN eicu_lab l ON l.patientunitstayid = c.patientunitstayid
            WHERE l.labresultoffset BETWEEN c.t0_offset AND c.t0_offset + 1440
              AND l.labname IN ({",".join(repr(k) for k in LAB_MAP)})
            GROUP BY 1, 2
        """).df().pivot(index="patientunitstayid", columns="feat", values="val")

        vital_aggs = ", ".join(
            f"AVG(v.{k}) AS {v}" for k, v in VITAL_MAP.items())
        vitals = con.execute(f"""
            SELECT c.patientunitstayid, {vital_aggs}
            FROM cohort_tbl c
            JOIN eicu_vital v ON v.patientunitstayid = c.patientunitstayid
            WHERE v.observationoffset BETWEEN c.t0_offset AND c.t0_offset + 1440
            GROUP BY 1
        """).df().set_index("patientunitstayid")

        feats = labs.join(vitals, how="outer")
        # eICU temperature is Celsius, as Challenge is. Verify rather than trust.
        verify_units(feats, "eICU mapped features")

        outcome = con.execute("""
            SELECT p.patientunitstayid,
                   CASE WHEN p.hospitaldischargestatus = 'Expired' THEN 1
                        WHEN p.hospitaldischargestatus = 'Alive' THEN 0 END AS died,
                   p.hospitalid,
                   MAX(TRY_CAST(a.predictedhospitalmortality AS DOUBLE)) AS apache_pred,
                   MAX(TRY_CAST(a.apachescore AS DOUBLE)) AS apache_score
            FROM eicu_patient p
            LEFT JOIN eicu_apache a ON a.patientunitstayid = p.patientunitstayid
                                    AND a.apacheversion = 'IVa'
            GROUP BY 1, 2, 3
        """).df().set_index("patientunitstayid")

        d = feats.join(outcome, how="inner").reset_index()
        d = d[d.died.notna()]
        log.info("  cohort with features and a mortality outcome: %d", len(d))
        log.info("  deaths: %d (%.1f%%)", int(d.died.sum()), 100 * d.died.mean())
        report_only("eicu_cohort_with_outcome", len(d))
        report_only("eicu_cohort_deaths", int(d.died.sum()))

    # --- apply the FROZEN set-A model ---------------------------------------
    with step(log, "apply frozen Challenge set-A model"):
        static = pd.read_parquet(paths.SCRATCH / "features" / "static.parquet")
        ref = con.execute(
            "SELECT patient_id, is_hyper_like_k2 FROM reference_assignment").df()
        train = static.merge(ref, on="patient_id", how="inner")
        tf = cfg["transferable_features"]
        train_feats = [f"{c}_mean" for c in tf["vitals"] + tf["labs"]
                       if f"{c}_mean" in static.columns]
        eicu_cols = [c.replace("_mean", "") for c in train_feats]
        usable = [(tc, ec) for tc, ec in zip(train_feats, eicu_cols) if ec in d.columns]
        log.info("  %d of %d transferable features exist in eICU: %s",
                 len(usable), len(train_feats), [e for _, e in usable])

        tr = train.dropna(subset=[t for t, _ in usable] + ["is_hyper_like_k2"])
        model = HistGradientBoostingClassifier(
            max_iter=200, max_depth=3, random_state=seed).fit(
            tr[[t for t, _ in usable]].to_numpy(float),
            tr.is_hyper_like_k2.to_numpy(int))
        log.info("  fitted on %d Challenge set-A patients, then FROZEN", len(tr))

        Xe = d[[e for _, e in usable]].to_numpy(float)
        d["pred_hyper"] = model.predict(Xe)
        d["prob_hyper"] = model.predict_proba(Xe)[:, 1]
        log.info("  predicted hyper-like prevalence in eICU: %.1f%%",
                 100 * d.pred_hyper.mean())

    # --- mortality gradient, with intervals reported wide -------------------
    with step(log, "mortality gradient and APACHE IVa benchmark"):
        rows = []
        for cls in (0, 1):
            g = d[d.pred_hyper == cls]
            k, n = int(g.died.sum()), len(g)
            lo, hi = stats.binomtest(k, n).proportion_ci() if n else (np.nan, np.nan)
            rows.append({"class": cls, "n": n, "deaths": k,
                         "mortality": round(k / n, 4) if n else None,
                         "ci_low": round(float(lo), 4), "ci_high": round(float(hi), 4)})
            log.info("  class %d: %d/%d died (%.1f%%, 95%% CI %.1f-%.1f%%)",
                     cls, k, n, 100 * k / n if n else 0, 100 * lo, 100 * hi)
        g1, g0 = d[d.pred_hyper == 1], d[d.pred_hyper == 0]
        p = float(stats.fisher_exact(
            [[int(g1.died.sum()), len(g1) - int(g1.died.sum())],
             [int(g0.died.sum()), len(g0) - int(g0.died.sum())]])[1])
        log.warning("  Fisher p = %.4f %s", p,
                    "" if p < 0.05 else "-> NOT significant; the intervals overlap "
                    "and n is small. Report the question as open (§6.1).")

        auc_endo = (float(roc_auc_score(d.died, d.prob_hyper))
                    if d.died.nunique() > 1 else None)
        sub = d[d.apache_pred.notna()]
        auc_apache = (float(roc_auc_score(sub.died, sub.apache_pred))
                      if len(sub) > 10 and sub.died.nunique() > 1 else None)
        log.warning("  AUC for hospital mortality:")
        log.warning("    our endotype probability : %s",
                    f"{auc_endo:.4f}" if auc_endo else "n/a")
        log.warning("    APACHE IVa (external)    : %s  (n=%d)",
                    f"{auc_apache:.4f}" if auc_apache else "n/a", len(sub))
        if auc_endo and auc_apache and auc_apache > auc_endo:
            log.warning("    APACHE IVa outperforms the endotype for mortality, which "
                        "is expected — it is a purpose-built severity model and the "
                        "endotype is not a mortality predictor. State it plainly.")
        report_only("eicu_auc_endotype_mortality", round(auc_endo, 4) if auc_endo else -1)
        report_only("eicu_auc_apache_mortality", round(auc_apache, 4) if auc_apache else -1)

    out = {
        "cohort_n": int(len(d)), "deaths": int(d.died.sum()),
        "mortality_rate": round(float(d.died.mean()), 4),
        "n_hospitals": int(d.hospitalid.nunique()),
        "features_transferred": [e for _, e in usable],
        "features_unavailable": [e for e in eicu_cols if e not in d.columns],
        "predicted_hyper_prevalence": round(float(d.pred_hyper.mean()), 4),
        "mortality_by_class": rows,
        "fisher_p": round(p, 4),
        "significant": bool(p < 0.05),
        "auc_mortality_endotype": round(auc_endo, 4) if auc_endo else None,
        "auc_mortality_apache_iva": round(auc_apache, 4) if auc_apache else None,
        "caveat": ("Small n and wide intervals by construction — the eICU demo is "
                   "~2,500 stays and the hypoxemic subset is far smaller. §6.1: if "
                   "this cannot support a stable estimate, the mortality question "
                   "stays open rather than being answered with a substitute."),
    }
    (paths.RESULTS / "L2_eicu_replication.json").write_text(json.dumps(out, indent=2))
    pd.DataFrame(rows).to_csv(paths.RESULTS / "L2_eicu_mortality.csv", index=False)
    log.info("wrote results/L2_eicu_replication.json")
    con.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
